-- =====================================================================
-- NomadHub — load RAW from the S3 stage
-- COPY INTO remembers which files it has loaded (64-day load metadata), so re-running
-- this script loads only NEW files — e.g. a new monthly BTS file or a new Airbnb
-- snapshot. That is what makes the daily Airflow run incremental.
-- Run as LOADER_ROLE after snowflake/01_raw_tables.sql.
-- =====================================================================
USE ROLE LOADER_ROLE;
USE WAREHOUSE NOMAD_WH;
USE SCHEMA NOMAD_HUB.RAW;

-- countries (6 columns)
COPY INTO COUNTRIES (ID, CODE, NAME, CONTINENT, WIKIPEDIA_LINK, KEYWORDS, _SOURCE_FILE, _LOADED_AT)
FROM (
    SELECT $1, $2, $3, $4, $5, $6,
           METADATA$FILENAME, CURRENT_TIMESTAMP()
    FROM @RAW_STAGE/countries/
)
PATTERN = '.*[.]csv[.]gz'
ON_ERROR = 'ABORT_STATEMENT';

-- regions (8 columns)
COPY INTO REGIONS (ID, CODE, LOCAL_CODE, NAME, CONTINENT, ISO_COUNTRY, WIKIPEDIA_LINK, KEYWORDS, _SOURCE_FILE, _LOADED_AT)
FROM (
