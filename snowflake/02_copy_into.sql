-- ── Sanity check: compare with data/raw/_manifest.json ──────────────────
SELECT 'countries' AS tbl, COUNT(*) AS row_count FROM COUNTRIES
UNION ALL SELECT 'regions',         COUNT(*) FROM REGIONS
UNION ALL SELECT 'airports',        COUNT(*) FROM AIRPORTS
UNION ALL SELECT 'listings',        COUNT(*) FROM LISTINGS
UNION ALL SELECT 'calendar',        COUNT(*) FROM CALENDAR
UNION ALL SELECT 'reviews',         COUNT(*) FROM REVIEWS
UNION ALL SELECT 'flights',         COUNT(*) FROM FLIGHTS
UNION ALL SELECT 'users',           COUNT(*) FROM USERS
UNION ALL SELECT 'stay_bookings',   COUNT(*) FROM STAY_BOOKINGS
UNION ALL SELECT 'flight_bookings', COUNT(*) FROM FLIGHT_BOOKINGS
ORDER BY row_count DESC;
